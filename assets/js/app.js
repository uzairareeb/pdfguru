/* PDFGuru shared helpers. Every tool page loads this before its tool script.
   Standard workspace DOM ids (generated by generator.py):
   dropzone, fileInput, fileList, optionsArea, processBtn,
   progressWrap, progressFill, progressLabel, resultArea, downloadBtn, resultInfo, errorMsg
*/
(function () {
  'use strict';

  function el(id) { return document.getElementById(id); }

  function fileSize(bytes) {
    if (!bytes && bytes !== 0) return '';
    if (bytes < 1024) return bytes + ' B';
    var kb = bytes / 1024;
    if (kb < 1024) return kb.toFixed(1) + ' KB';
    var mb = kb / 1024;
    if (mb < 1024) return mb.toFixed(2) + ' MB';
    return (mb / 1024).toFixed(2) + ' GB';
  }

  function readAsArrayBuffer(file) {
    return new Promise(function (resolve, reject) {
      var r = new FileReader();
      r.onload = function () { resolve(r.result); };
      r.onerror = function () { reject(new Error('Could not read file: ' + file.name)); };
      r.readAsArrayBuffer(file);
    });
  }

  function downloadBlob(blob, filename) {
    var url = URL.createObjectURL(blob);
    var a = el('downloadBtn');
    if (a) {
      a.href = url;
      a.setAttribute('download', filename);
    } else {
      // fallback: programmatic click
      var tmp = document.createElement('a');
      tmp.href = url;
      tmp.download = filename;
      document.body.appendChild(tmp);
      tmp.click();
      setTimeout(function () { document.body.removeChild(tmp); }, 500);
      setTimeout(function () { URL.revokeObjectURL(url); }, 5000);
    }
  }

  function setProgress(pct, label) {
    var wrap = el('progressWrap'), fill = el('progressFill'), lab = el('progressLabel');
    if (wrap) wrap.hidden = false;
    if (fill) fill.style.width = Math.max(0, Math.min(100, pct)) + '%';
    if (lab && label !== undefined) lab.textContent = label;
  }

  function resetWork() {
    var e = el('errorMsg'); if (e) { e.hidden = true; e.textContent = ''; }
    var r = el('resultArea'); if (r) r.hidden = true;
    setProgress(0, '');
  }

  function fail(msg) {
    var w = el('progressWrap'); if (w) w.hidden = true;
    var e = el('errorMsg');
    if (e) {
      e.hidden = false;
      e.textContent = 'Something went wrong: ' + msg + ' Please try a different file.';
    } else {
      alert('Something went wrong: ' + msg);
    }
  }

  function done(blob, filename, info) {
    var w = el('progressWrap'); if (w) w.hidden = true;
    downloadBlob(blob, filename);
    var r = el('resultArea'); if (r) r.hidden = false;
    var i = el('resultInfo');
    if (i) i.textContent = info || ('Your file is ready: ' + filename + ' (' + fileSize(blob.size) + ')');
    var btn = el('processBtn'); if (btn) btn.disabled = false;
    if (r) r.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }

  // Wire a dropzone + hidden file input. opts: {zoneId, inputId, accept, multiple, onFiles}
  function bindDropzone(opts) {
    var zone = el(opts.zoneId || 'dropzone');
    var input = el(opts.inputId || 'fileInput');
    if (!zone || !input) return;
    if (opts.accept) input.setAttribute('accept', opts.accept);
    if (opts.multiple) input.setAttribute('multiple', 'multiple');
    zone.addEventListener('click', function (ev) {
      if (ev.target.closest('button') || ev.target.closest('a')) return;
      input.click();
    });
    zone.addEventListener('dragover', function (ev) { ev.preventDefault(); zone.classList.add('dragover'); });
    zone.addEventListener('dragleave', function () { zone.classList.remove('dragover'); });
    zone.addEventListener('drop', function (ev) {
      ev.preventDefault();
      zone.classList.remove('dragover');
      if (ev.dataTransfer && ev.dataTransfer.files && ev.dataTransfer.files.length) {
        opts.onFiles(Array.prototype.slice.call(ev.dataTransfer.files));
      }
    });
    input.addEventListener('change', function () {
      if (input.files && input.files.length) {
        opts.onFiles(Array.prototype.slice.call(input.files));
        input.value = '';
      }
    });
  }

  function isPdf(file) {
    return file && (file.type === 'application/pdf' || /\.pdf$/i.test(file.name));
  }

  function isImage(file) {
    return file && (file.type.indexOf('image/') === 0 || /\.(jpe?g|png|webp|gif|bmp)$/i.test(file.name));
  }

  function baseName(name) {
    return name.replace(/\.[^.]+$/, '');
  }

  // Yield to the UI thread so progress bars repaint during heavy loops.
  function tick() { return new Promise(function (res) { setTimeout(res, 0); }); }

  window.PG = {
    el: el,
    fileSize: fileSize,
    readAsArrayBuffer: readAsArrayBuffer,
    downloadBlob: downloadBlob,
    setProgress: setProgress,
    resetWork: resetWork,
    fail: fail,
    done: done,
    bindDropzone: bindDropzone,
    isPdf: isPdf,
    isImage: isImage,
    baseName: baseName,
    tick: tick
  };
})();
